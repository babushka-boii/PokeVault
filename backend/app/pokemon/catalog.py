"""The fixed species index: names (English, Spanish) and types of all 1025 species.

The data lives in ``data/species_index.json`` (versioned in the repo and generated by
``scripts/build_species_index.py``), so it needs no network, survives restarts and
never changes under a visitor. A file that does not validate is a startup error:
there is never a partial index.
"""

import hashlib
import json
import re
import unicodedata
from collections.abc import Sequence
from functools import lru_cache
from pathlib import Path
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, ValidationError, field_validator

from app.pokemon.schemas import NATIONAL_DEX_TOTAL

DATA_FILE = Path(__file__).parent / "data" / "species_index.json"
POKEMON_TYPES = (
    "normal", "fire", "water", "electric", "grass", "ice", "fighting", "poison",
    "ground", "flying", "psychic", "bug", "rock", "ghost", "dragon", "dark", "steel",
    "fairy",
)  # fmt: skip
_CONTROL = re.compile(r"[\x00-\x1f\x7f]")


class SpeciesIndexInvalid(Exception):
    """The species index file is missing, unreadable or inconsistent."""


class SpeciesRow(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)

    number: int = Field(ge=1, le=NATIONAL_DEX_TOTAL)
    name_en: str = Field(min_length=1, max_length=100)
    name_es: str = Field(min_length=1, max_length=100)
    types: list[str] = Field(min_length=1, max_length=2)

    @field_validator("name_en", "name_es")
    @classmethod
    def clean_name(cls, value: str) -> str:
        if (
            not value.strip()
            or _CONTROL.search(value)
            or value != " ".join(value.split())
        ):
            raise ValueError("Invalid species name")
        return value

    @field_validator("types")
    @classmethod
    def valid_types(cls, value: list[str]) -> list[str]:
        if len(set(value)) != len(value) or any(
            kind not in POKEMON_TYPES for kind in value
        ):
            raise ValueError("Invalid species types")
        return value


def validate_species(rows: Sequence[Any]) -> list[SpeciesRow]:
    """Exactly one valid row per national number, in order."""
    try:
        species = [SpeciesRow.model_validate(row) for row in rows]
    except ValidationError as error:
        raise SpeciesIndexInvalid("Invalid species row") from error
    if [row.number for row in species] != list(range(1, NATIONAL_DEX_TOTAL + 1)):
        raise SpeciesIndexInvalid("The species index must list 1..1025 once, in order")
    return species


def normalize_name(value: str) -> str:
    """Lower case, without accents or punctuation; ♀ and ♂ become f and m."""
    value = value.lower().replace("♀", "f").replace("♂", "m")
    return "".join(
        char
        for char in unicodedata.normalize("NFKD", value)
        if char.isalnum() and not unicodedata.combining(char)
    )


class SpeciesCatalog:
    def __init__(self, rows: list[SpeciesRow], etag: str) -> None:
        self.rows = rows
        self.etag = etag
        self.keys = [
            (normalize_name(row.name_en), normalize_name(row.name_es)) for row in rows
        ]


def load_catalog(path: Path = DATA_FILE) -> SpeciesCatalog:
    try:
        raw = path.read_bytes()
        data = json.loads(raw)
        rows = validate_species(data["species"])
    except SpeciesIndexInvalid:
        raise
    except (OSError, ValueError, KeyError, TypeError) as error:
        raise SpeciesIndexInvalid("The species index cannot be read") from error
    return SpeciesCatalog(rows, f'"{hashlib.sha256(raw).hexdigest()[:32]}"')


@lru_cache(maxsize=1)
def get_catalog() -> SpeciesCatalog:
    return load_catalog()
